#!/usr/bin/env node
/**
 * Extracts command names from the bot's generated docs/COMMANDS.md.
 * Safe to run from site/, requires no dependencies, never modifies bot sources.
 * When docs are unavailable, retains the included documented-command preview.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docs = resolve(site, '../docs/COMMANDS.md');
const output = resolve(site, 'src/data/commands.generated.json');
const commonGroups = new Set([
  'setup','diagnose','utility','moderation','mod','config','roles','role',
  'channels','channel','economy','xp','level','levels','giveaways','giveaway',
  'polls','poll','events','event','reminders','reminder','welcome','audio',
  'music','tags','tag','tickets','ticket','suggestions','suggestion','starboard',
  'reactionroles','reactionrole','fun','games','game','avatar','images','image',
  'bookmarks','bookmark','notes','note','tasks','task','admin','server',
  'userinfo','info','help','leaderboard','automod'
]);

function tidy(s) {
  return s.replace(/<[^>]*>/g,'').replace(/\*\*/g,'').replace(/\[([^\]]+)\]\([^)]+\)/g,'$1')
    .replace(/`/g,'').replace(/\\\|/g,'|').replace(/\s+/g,' ').trim().slice(0, 180);
}

function findCommands(line) {
  const found = [];
  // Prefer inline-code snippets generated by command-reference tools.
  for (const match of line.matchAll(/`(\/[^`\n]+)`/g)) {
    const command = match[1].replace(/\s*\[[^\]]*\]/g,'').replace(/\s*<[^>]*>/g,'').trim();
    const names = command.match(/^\/[a-z][\w-]*(?:\s+[a-z][\w-]*){0,2}/i);
    if (names) found.push(names[0].toLowerCase());
  }
  // Headings and plain-text command columns may not use backticks.
  if (!found.length && (/^\s*#+\s*\//.test(line) || /^\s*\|\s*\//.test(line) || /^\s*[-*]\s*\//.test(line))) {
    const match = line.match(/\/\b[a-z][\w-]*(?:\s+[a-z][\w-]*){0,2}/i);
    if (match) found.push(match[0].toLowerCase());
  }
  return found;
}

if (!existsSync(docs)) {
  console.log('[commands] ../docs/COMMANDS.md unavailable. Keeping documented command previews.');
  process.exit(0);
}

const text = await readFile(docs, 'utf8');
const commands = new Map();
let heading = '';
let inFence = false;
for (const raw of text.split(/\r?\n/)) {
  const line = raw.trim();
  if (/^```/.test(line)) { inFence = !inFence; continue; }
  if (inFence) continue;
  const headingMatch = line.match(/^#{1,5}\s+(.+)$/);
  if (headingMatch) heading = tidy(headingMatch[1]);
  const found = findCommands(line);
  for (const name of found) {
    if (name.length > 85) continue;
    const group = name.slice(1).split(' ')[0];
    if (!/^[a-z][\w-]*$/.test(group)) continue;
    // If a doc line has an adjacent description column, prefer it.
    const cells = line.startsWith('|') ? line.split('|').map(tidy).filter(Boolean) : [];
    let description = '';
    if (cells.length > 1) {
      const idx = cells.findIndex(c => c.toLowerCase().includes(name));
      if (idx >= 0) description = cells.slice(idx + 1).find(c => c.length > 8 && !/^\//.test(c)) ?? '';
    }
    if (!description && /\s[—–-]\s/.test(line)) description = tidy(line.split(/\s[—–-]\s/).slice(1).join(' - '));
    if (!description && line.startsWith('-')) description = tidy(line.replace(/^[-*]\s*/, '').replace(/`[^`]*`/g, ''));
    if (!description && heading && !heading.startsWith('/')) description = `${heading} command`;
    if (!description) description = 'View the command reference for syntax and permissions.';
    // Filter incidental slash-commands in general prose by requiring either a familiar group
    // or a table/doc heading context; this is a best-effort reference index, not registration.
    if (!commonGroups.has(group) && !line.startsWith('|') && !/^#+\s*\//.test(line) && !/^[-*]\s*`\//.test(line)) continue;
    const previous = commands.get(name);
    if (!previous || (previous.description.endsWith(' command') && !description.endsWith(' command'))) {
      commands.set(name, { name, group, description });
    }
  }
}

if (commands.size < 8) {
  console.warn(`[commands] Only ${commands.size} commands detected; leaving preview untouched. Check docs/COMMANDS.md formatting.`);
  process.exit(0);
}
const entries = [...commands.values()].sort((a,b) => a.group.localeCompare(b.group) || a.name.localeCompare(b.name));
await mkdir(dirname(output), { recursive: true });
await writeFile(output, JSON.stringify({ source: 'docs/COMMANDS.md', generatedAt: new Date().toISOString(), commands: entries }, null, 2) + '\n');
console.log(`[commands] Synced ${entries.length} documented command paths from ../docs/COMMANDS.md.`);
console.log('[commands] This index is derived from documentation; counts and live API behavior are verified separately.');
